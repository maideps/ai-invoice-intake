"""The lock files match pyproject.toml (D-018).

``requirements.lock`` (the image) and ``requirements-dev.lock`` (development and CI) are
generated by ``npm run lock:backend``. These tests fail when someone changes the dependencies in
``pyproject.toml`` without regenerating the locks, or edits a lock by hand.
"""

import re
from dataclasses import dataclass
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parents[1]
PYPROJECT = (BACKEND / "pyproject.toml").read_text(encoding="utf-8")


@dataclass(frozen=True)
class Pin:
    name: str
    version: str
    marker: str
    hashes: int


def declared(list_header: str) -> list[Requirement]:
    """The quoted requirements in a ``name = [ ... ]`` list of pyproject.toml."""
    block = re.search(rf"^{re.escape(list_header)} = \[(.*?)^\]", PYPROJECT, re.M | re.S)
    assert block, f"no {list_header} list in pyproject.toml"
    return [Requirement(text) for text in re.findall(r'^\s*"([^"]+)"', block.group(1), re.M)]


def pins(lock: str) -> list[Pin]:
    """Every requirement entry of a uv-generated lock, with its marker and hash count."""
    text = (BACKEND / lock).read_text(encoding="utf-8")
    entries = re.split(r"\n(?=[A-Za-z0-9])", text.split("\n", 2)[2])
    found = []
    for entry in entries:
        head = entry.split("\\", 1)[0].strip()
        match = re.fullmatch(r"([A-Za-z0-9._-]+)==([^\s;]+)(?:\s*;\s*(.+))?", head)
        assert match, f"{lock}: not an exact pin: {head!r}"
        name, version, marker = match.groups()
        found.append(Pin(canonicalize_name(name), version, marker or "", entry.count("--hash=")))
    return found


RUNTIME = declared("dependencies")
DEV = RUNTIME + declared("dev")
LOCKS = {"requirements.lock": RUNTIME, "requirements-dev.lock": DEV}


@pytest.mark.parametrize("lock", LOCKS)
def test_the_lock_was_generated_for_every_platform_with_hashes(lock: str) -> None:
    header = (BACKEND / lock).read_text(encoding="utf-8").splitlines()[1]

    assert "uv pip compile pyproject.toml" in header
    assert "--universal" in header
    assert "--generate-hashes" in header
    assert all(pin.hashes > 0 for pin in pins(lock)), f"{lock} has an entry without hashes"


@pytest.mark.parametrize(("lock", "requirements"), LOCKS.items())
def test_every_declared_dependency_is_pinned_within_its_range(
    lock: str, requirements: list[Requirement]
) -> None:
    locked = {pin.name: pin.version for pin in pins(lock)}

    for requirement in requirements:
        name = canonicalize_name(requirement.name)
        assert name in locked, f"{requirement} is not in {lock}; run: npm run lock:backend"
        assert requirement.specifier.contains(locked[name], prereleases=True), (
            f"{lock} pins {name}=={locked[name]}, outside {requirement}; run: npm run lock:backend"
        )


def test_the_image_and_the_tests_use_the_same_versions() -> None:
    runtime = {(pin.name, pin.marker): pin.version for pin in pins("requirements.lock")}
    dev = {(pin.name, pin.marker): pin.version for pin in pins("requirements-dev.lock")}

    different = {key: (version, dev.get(key)) for key, version in runtime.items()}
    different = {key: pair for key, pair in different.items() if pair[0] != pair[1]}
    assert not different, f"the locks disagree (runtime, dev): {different}"
